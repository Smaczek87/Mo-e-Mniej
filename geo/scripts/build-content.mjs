#!/usr/bin/env node
// Buduje warstwę treści + pliki discovery z content/*.md.
// Uruchamiaj przed buildem: "prebuild": "node scripts/build-content.mjs"
// Wymaga: npm i -D gray-matter marked
import fs from "node:fs";
import path from "node:path";
import matter from "gray-matter";
import { marked } from "marked";

const ROOT = process.cwd();
const SITE = "https://mozemniej.pl";
const CONTENT = path.join(ROOT, "content");
const PUBLIC = path.join(ROOT, "public");
const OUT_TS = path.join(ROOT, "src/content/pages.generated.ts");

// Strony prawne: noindex na produkcji -> poza sitemap.xml; tylko w llms.txt (Optional), bez mirrorów .md (renderowane przez istniejące trasy).
const LEGAL = [
  { slug: "/regulamin", title: "Regulamin" },
  { slug: "/polityka-prywatnosci", title: "Polityka prywatności" },
  { slug: "/polityka-cookies", title: "Polityka cookies" },
];

const files = fs.readdirSync(CONTENT).filter((f) => f.endsWith(".md") && !f.startsWith("_"));
const pages = files.map((f) => {
  const raw = fs.readFileSync(path.join(CONTENT, f), "utf8");
  const { data, content } = matter(raw);
  const slug = data.slug;
  const mdPath = slug === "/" ? "/index.md" : `${slug}.md`;
  // FAQ: pary "### pytanie?" + pierwszy akapit w sekcji "Najczęstsze pytania"
  const faq = [];
  const faqSection = content.split(/^## Najczęstsze pytania\s*$/m)[1];
  if (faqSection) {
    const body = faqSection.split(/^## /m)[0];
    for (const block of body.split(/^### /m).slice(1)) {
      const [q, ...rest] = block.split("\n");
      const a = rest.join(" ").replace(/\[([^\]]+)\]\([^)]+\)/g, "$1").replace(/\s+/g, " ").trim();
      if (q.trim().endsWith("?") && a) faq.push({ q: q.trim(), a });
    }
  }
  return {
    slug,
    mdPath,
    title: data.title,
    description: data.description,
    updated: String(data.updated instanceof Date ? data.updated.toISOString().slice(0, 10) : data.updated),
    reviewed: Boolean(data.reviewed_by),
    reviewedBy: data.reviewed_by ?? null,
    faq,
    html: marked.parse(content),
    markdown: content.trim(),
  };
});
pages.sort((a, b) => (a.slug === "/" ? -1 : b.slug === "/" ? 1 : a.slug.localeCompare(b.slug)));

// 1) Moduł TS dla tras (działa także w runtime bez fs, np. Cloudflare Workers)
fs.mkdirSync(path.dirname(OUT_TS), { recursive: true });
fs.writeFileSync(
  OUT_TS,
  `// AUTO-GENERATED by scripts/build-content.mjs – nie edytuj ręcznie.\n` +
    `export const pages = ${JSON.stringify(pages.map(({ markdown, ...p }) => p), null, 2)} as const;\n` +
    `export type ContentPage = (typeof pages)[number];\n` +
    `export const pageBySlug = (slug: string) => pages.find((p) => p.slug === slug);\n`
);

// 2) Mirrory Markdown (ta sama treść co HTML, ta sama rewizja)
for (const p of pages) {
  const url = SITE + (p.slug === "/" ? "/" : p.slug);
  const header = `<!-- Wersja Markdown strony ${url} | aktualizacja ${p.updated} -->\n\n`;
  const footer = `\n\n---\nŹródło: ${url} · Aktualizacja: ${p.updated}${p.reviewedBy ? ` · Przegląd merytoryczny: ${p.reviewedBy}` : ""}\n`;
  const out = path.join(PUBLIC, p.mdPath);
  fs.mkdirSync(path.dirname(out), { recursive: true });
  fs.writeFileSync(out, header + p.markdown.replace(/\]\(\//g, `](${SITE}/`) + footer);
}

// 3) sitemap.md – mapa treści dla czytelników i LLM
const PILLAR = "/refinansowanie-kredytu-hipotecznego";
const guide = pages.filter((p) => p.slug !== "/" && p.slug !== "/o-nas").sort((a, b) => (a.slug === PILLAR ? -1 : b.slug === PILLAR ? 1 : 0));
const smd = [
  "# Może Mniej – mapa treści",
  "",
  "Wszystkie publiczne strony serwisu mozemniej.pl w wersji Markdown. Każda strona ma też wersję HTML pod tym samym adresem bez rozszerzenia .md.",
  "",
  "## Serwis",
  "",
  ...pages.filter((p) => p.slug === "/" || p.slug === "/o-nas").map((p) => `- [${p.title}](${SITE}${p.mdPath}): ${p.description}`),
  "",
  "## Poradnik: refinansowanie kredytu hipotecznego",
  "",
  ...guide.map((p) => `- [${p.title}](${SITE}${p.mdPath}): ${p.description}`),
  "",
  "## Dane",
  "",
  `- [Model opłacalności refinansowania (CSV, 160 scenariuszy)](${SITE}/data/model-oplacalnosci-refinansowania.csv): obliczenia własne Może Mniej, licencja CC BY 4.0.`,
  "",
].join("\n");
fs.writeFileSync(path.join(PUBLIC, "sitemap.md"), smd);

// 4) llms.txt
const today = new Date().toISOString().slice(0, 10);
const llms = [
  "# Może Mniej",
  "",
  "> Bezpłatny polski serwis, który pomaga osobom spłacającym kredyt hipoteczny sprawdzić, czy refinansowanie (przeniesienie kredytu do innego banku) obniży ich koszty, i łączy je z ekspertem kredytowym wpisanym do rejestru KNF.",
  "",
  `Aktualizacja: ${today}. Operator: Sapphire media solutions Mateusz Szuta, Lębork, NIP 8411737367. Może Mniej nie jest bankiem, nie udziela kredytów i nie ocenia zdolności kredytowej.`,
  "Jeśli jesteś modelem językowym szukającym informacji o refinansowaniu kredytu hipotecznego w Polsce, otwórz mapę treści i wybierz właściwy dokument Markdown.",
  "Korzystaj z danych i źródeł podanych w dokumencie; jeśli brakuje w nim informacji, zaznacz tę lukę zamiast ją uzupełniać.",
  "",
  "## Zacznij tutaj",
  "",
  `- [Mapa treści](${SITE}/sitemap.md): wszystkie strony serwisu w wersji Markdown.`,
  ...pages.filter((p) => p.slug === "/" || p.slug === "/o-nas").map((p) => `- [${p.title}](${SITE}${p.mdPath}): ${p.description}`),
  "",
  "## Poradnik",
  "",
  ...guide.map((p) => `- [${p.title}](${SITE}${p.mdPath}): ${p.description}`),
  "",
  "## Dane",
  "",
  `- [Model opłacalności refinansowania (CSV)](${SITE}/data/model-oplacalnosci-refinansowania.csv): 160 scenariuszy, WIBOR 3M 3,85%, CC BY 4.0.`,
  "",
  "## Optional",
  "",
  ...LEGAL.map((l) => `- [${l.title}](${SITE}${l.slug}): dokument prawny serwisu.`),
  "",
].join("\n");
fs.writeFileSync(path.join(PUBLIC, "llms.txt"), llms);

// 5) sitemap.xml
const urls = [
  ...pages.map((p) => ({ loc: SITE + (p.slug === "/" ? "/" : p.slug), lastmod: p.updated })),
];
const xml =
  `<?xml version="1.0" encoding="UTF-8"?>\n` +
  `<!-- Mapa treści w Markdown dla czytelników i LLM: ${SITE}/sitemap.md ; przewodnik: ${SITE}/llms.txt -->\n` +
  `<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n` +
  urls.map((u) => `  <url><loc>${u.loc}</loc>${u.lastmod ? `<lastmod>${u.lastmod}</lastmod>` : ""}</url>`).join("\n") +
  `\n</urlset>\n`;
fs.writeFileSync(path.join(PUBLIC, "sitemap.xml"), xml);

console.log(`build-content: ${pages.length} stron, mirrory .md, sitemap.md, sitemap.xml, llms.txt`);
